/**
 * Failover counters, exposed for diagnostics.
 *
 * A provider that times out after 15 s and silently falls through to the next
 * one is indistinguishable from normal operation — which made every "the
 * assistant is slow" report impossible to diagnose. Every failover is now
 * logged with its cause and elapsed time, and counted per provider.
 */
const providerFailures: Record<string, number> = {};

function logProviderFailure(provider: string, startedAt: number, error: unknown): void {
  providerFailures[provider] = (providerFailures[provider] ?? 0) + 1;
  const elapsed = Date.now() - startedAt;
  const cause = error instanceof Error ? error.message : String(error);
  console.warn(
    `[ai] provider "${provider}" failed after ${elapsed}ms — falling back. ` +
      `cause: ${cause} (failures so far: ${providerFailures[provider]})`,
  );
}

export function getProviderFailureCounts(): Readonly<Record<string, number>> {
  return { ...providerFailures };
}

export interface AssistantChatRequest {
  message: string;
  history?: ChatMessage[];
  context?: {
    reportId?: string;
    filters?: Record<string, unknown>;
  };
  /** Current Power BI report state (page, filters, bookmarks) — injected into the AI context. */
  powerbiState?: {
    activePage: string | null;
    activePageDisplayName: string | null;
    filters: Array<{ table: string; column: string; operator: string; values: string[] }>;
    pages: Array<{ name: string; displayName: string }>;
    bookmarks: Array<{ name: string; displayName: string }>;
  };
  /** Feedback from previous command execution (for auto-correction loop). */
  executionFeedback?: Array<{
    action: string;
    success: boolean;
    error?: string;
  }>;
  /** Caller identity, forwarded to the backend policy engine. */
  userRole?: string | null;
  userEmail?: string | null;
}

export interface AssistantChatResponse {
  reply: string;
  /** Structured commands the client should execute to control the platform. */
  commands?: AgentCommand[];
  mlRequested?: boolean;
  suggestions?: string[];
  /** Agent status from the LangGraph backend: "done" | "awaiting_clarification". */
  status?: string;
  /** Clarification question generated by the agent when the request is ambiguous. */
  clarification?: string;
  /** Intent detected by the agent's context analysis node. */
  intent?: string;
}

