/**
 * Call OpenAI Chat Completions API to generate a response.
 *
 * Requires OPENAI_API_KEY in environment variables.
 */
interface LLMResult {
  text: string;
  commands: AgentCommand[];
  suggestions?: string[];
  status?: string;
  clarification?: string;
  intent?: string;
}

async function callOpenAI(
  message: string,
  history?: ChatMessage[],
  executionFeedback?: Array<{ action: string; success: boolean; error?: string }>
): Promise<LLMResult> {
  const [apiKey, model] = await Promise.all([
    getSetting("openai_api_key"),
    getSetting("openai_model"),
  ]);
  if (!apiKey) {
    throw new Error("OPENAI_API_KEY is not configured");
  }

  // Build the user message, optionally including execution feedback for auto-correction
  let userContent = message;
  if (executionFeedback && executionFeedback.length > 0) {
    const failedActions = executionFeedback.filter((f) => !f.success);
    const succeededActions = executionFeedback.filter((f) => f.success);

    const feedbackParts: string[] = [];
    if (succeededActions.length > 0) {
      feedbackParts.push(
        `Successfully executed: ${succeededActions.map((f) => f.action).join(", ")}`
      );
    }
    if (failedActions.length > 0) {
      feedbackParts.push(
        `Failed actions:\n${failedActions
          .map((f) => `- ${f.action}: ${f.error}`)
          .join("\n")}\n\nPlease retry the failed actions with corrected arguments or a different approach.`
      );
    }
    userContent = `${message}\n\n[EXECUTION FEEDBACK]\n${feedbackParts.join("\n")}`;
  }

  const messages = [
    { role: "system", content: SYSTEM_PROMPT },
    ...(history ?? []).map((m) => ({
      role: m.role,
      content: m.content,
    })),
    { role: "user", content: userContent },
  ];

  const res = await fetch("https://api.openai.com/v1/chat/completions", {
    method: "POST",
    headers: {
      Authorization: `Bearer ${apiKey}`,
      "Content-Type": "application/json",
    },
    body: JSON.stringify({
      model: model || DEFAULT_OPENAI_MODEL,
      messages,
      // GPT-6 Luna only accepts tools and a non-default temperature on Chat
      // Completions when reasoning is disabled.
      reasoning_effort: "none",
      temperature: 0.4,
      max_completion_tokens: 800,
      tools: buildOpenAITools(),
      tool_choice: "auto",
    }),
  });

  if (!res.ok) {
    const error = await res.text();
    throw new Error(`OpenAI API error: ${error}`);
  }

  const data = await res.json();
  const choice = data.choices?.[0]?.message;
  const commands = parseToolCalls(choice?.tool_calls);
  const rawText: string = choice?.content ?? "";
  const { text, suggestions } = extractSuggestions(rawText);

  return { text, commands, suggestions };
}

/**
 * Extract [[SUGGESTIONS]]...[[/SUGGESTIONS]] block from LLM text response.
 * Returns the cleaned text (without the block) and the parsed suggestions array.
 */
function extractSuggestions(text: string): { text: string; suggestions?: string[] } {
  const match = text.match(/\[\[SUGGESTIONS\]\]\s*([\s\S]*?)\[\[\/SUGGESTIONS\]\]/);
  if (!match) return { text };
  try {
    const suggestions = JSON.parse(match[1].trim());
    if (!Array.isArray(suggestions)) return { text };
    const cleaned = text.replace(match[0], "").trim();
    return { text: cleaned, suggestions: suggestions.filter((s) => typeof s === "string") };
  } catch {
    return { text };
  }
}

/**
 * Convert OpenAI tool_calls into validated AgentCommand objects.
 * Unknown tools and malformed arguments are silently dropped.
 */
function parseToolCalls(toolCalls: unknown): AgentCommand[] {
  if (!Array.isArray(toolCalls)) return [];
  const commands: AgentCommand[] = [];

  for (const call of toolCalls) {
    const name = call?.function?.name;
    if (!name || !COMMANDS[name]) continue;

    let args: Record<string, unknown> = {};
    const raw = call?.function?.arguments;
    if (typeof raw === "string" && raw.trim()) {
      try {
        args = JSON.parse(raw);
      } catch {
        args = {};
      }
    }
    commands.push({ action: name, args });
  }

  return commands;
}

/**
 * Call Anthropic Messages API to generate a response.
 *
 * Requires ANTHROPIC_API_KEY in environment variables.
 */
async function callAnthropic(
  message: string,
  history?: ChatMessage[]
): Promise<string> {
  const [apiKey, model] = await Promise.all([
    getSetting("anthropic_api_key"),
    getSetting("anthropic_model"),
  ]);
  if (!apiKey) {
    throw new Error("ANTHROPIC_API_KEY is not configured");
  }

  const messages = [
    ...(history ?? []).map((m) => ({
      role: m.role,
      content: m.content,
    })),
    { role: "user", content: message },
  ];

  const res = await fetch("https://api.anthropic.com/v1/messages", {
    method: "POST",
    headers: {
      "x-api-key": apiKey,
      "Content-Type": "application/json",
      "anthropic-version": "2023-06-01",
    },
    body: JSON.stringify({
      model: model || "claude-sonnet-4-20250514",
      system: SYSTEM_PROMPT,
      messages,
      max_tokens: 800,
    }),
  });

  if (!res.ok) {
    const error = await res.text();
    throw new Error(`Anthropic API error: ${error}`);
  }

  const data = await res.json();
  return data.content[0]?.text ?? "I could not generate a response.";
}

/**
 * Proxy to the FastAPI backend (LangGraph agent) when FASTAPI_URL is set.
 * The backend runs the full LangGraph pipeline: Intent → Planner → Tools → Verification → Response.
 */
async function callFastAPI(
  message: string,
  history?: ChatMessage[],
  identity?: { userRole?: string | null; userEmail?: string | null },
): Promise<LLMResult | null> {
  const url = await getSetting("fastapi_url");
  if (!url) return null;

  const res = await fetch(`${url}/api/agent/chat`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({
      message,
      history: (history ?? []).map((m) => ({ role: m.role, content: m.content })),
      user_role: identity?.userRole ?? "viewer",
      user_email: identity?.userEmail ?? "",
    }),
  });

  if (!res.ok) {
    throw new Error(`FastAPI error: ${await res.text()}`);
  }

  const data = await res.json();

  // Single-analysis architecture: the agent already ran the DHIS2 analysis
  // server-side (Supabase-first) and returns the complete structured payload.
  // Inject it into the run_dhis2_analysis command args so the frontend renders
  // it directly — no second metric search, no divergent results.
  const analysisPayload = data.analysis_payload;
  const commands: AgentCommand[] = (data.actions ?? []).map(
    (a: { action: string; args?: Record<string, unknown> }) => {
      if (a.action === "run_dhis2_analysis" && analysisPayload) {
        return {
          action: a.action,
          args: { ...(a.args ?? {}), analysisPayload },
        };
      }
      return { action: a.action, args: a.args };
    }
  );

  return {
    text: data.response ?? "",
    commands,
    status: data.status,
    clarification: data.clarification ?? undefined,
    intent: data.intent ?? undefined,
  };
}

/**
 * Generate an AI assistant response using the configured LLM provider.
 *
 * Priority: FASTAPI_URL (LangGraph) > OPENAI_API_KEY > ANTHROPIC_API_KEY
 * Falls back to a simple rule-based response if no provider is configured.
 */
export async function generateAssistantResponse(
  req: AssistantChatRequest
): Promise<AssistantChatResponse> {
  const { message, history, executionFeedback, powerbiState, userRole, userEmail } = req;

  // Inject Power BI report state into the user message context
  let contextualizedMessage = message;
  if (powerbiState) {
    const stateParts: string[] = [];
    if (powerbiState.activePageDisplayName) {
      stateParts.push(`Page active: ${powerbiState.activePageDisplayName}`);
    }
    if (powerbiState.filters.length > 0) {
      const filterDesc = powerbiState.filters
        .map((f) => `${f.table}.${f.column}=${f.values.join(",")}`)
        .join("; ");
      stateParts.push(`Filtres actifs: ${filterDesc}`);
    }
    if (powerbiState.pages.length > 0) {
      stateParts.push(
        `Pages disponibles: ${powerbiState.pages.map((p) => p.displayName).join(", ")}`,
      );
    }
    if (powerbiState.bookmarks.length > 0) {
      stateParts.push(
        `Bookmarks disponibles: ${powerbiState.bookmarks.map((b) => b.displayName).join(", ")}`,
      );
    }
    if (stateParts.length > 0) {
      contextualizedMessage = `${message}\n\n[POWER BI CONTEXT]\n${stateParts.join("\n")}`;
    }
  }

  // Check for ML-related requests
  const mlKeywords = ["forecast", "predict", "anomaly", "trend", "projection", "prévision", "prédiction", "anomalie", "tendance"];
  const mlRequested = mlKeywords.some((kw) =>
    message.toLowerCase().includes(kw)
  );

  let reply = "";
  let commands: AgentCommand[] = [];
  let suggestions: string[] | undefined;
  let status: string | undefined;
  let clarification: string | undefined;
  let intent: string | undefined;

  const [fastApiUrl, openAiKey, anthropicKey] = await Promise.all([
    getSetting("fastapi_url"),
    getSetting("openai_api_key"),
    getSetting("anthropic_api_key"),
  ]);

  // ─── Priority 1: FastAPI backend (LangGraph agent) ───────
  if (fastApiUrl) {
    const startedAt = Date.now();
    try {
      const fastapiResult = await callFastAPI(contextualizedMessage, history, { userRole, userEmail });
      if (fastapiResult) {
        reply = fastapiResult.text;
        commands = fastapiResult.commands;
        status = fastapiResult.status;
        clarification = fastapiResult.clarification;
        intent = fastapiResult.intent;
      }
    } catch (err) {
      logProviderFailure("fastapi", startedAt, err);
    }
  }

  // ─── Priority 2: OpenAI direct (with tool-calling) ───────
  if (!reply && commands.length === 0 && openAiKey) {
    const startedAt = Date.now();
    try {
      const result = await callOpenAI(contextualizedMessage, history, executionFeedback);
      reply = result.text;
      commands = result.commands;
      suggestions = result.suggestions;
    } catch (err) {
      logProviderFailure("openai", startedAt, err);
    }
  }

  // ─── Priority 3: Anthropic (text only, no platform control) ──
  if (!reply && commands.length === 0 && anthropicKey) {
    const startedAt = Date.now();
    try {
      reply = await callAnthropic(contextualizedMessage, history);
    } catch (err) {
      logProviderFailure("anthropic", startedAt, err);
    }
  }

  // If the LLM triggered commands but returned no text, synthesize a reply.
  if (!reply && commands.length > 0) {
    reply = buildDefaultReply(commands);
  }

  // Last-resort fallback when no provider is configured/available.
  if (!reply && commands.length === 0) {
    reply = generateFallbackResponse();
  }

  return { reply, commands, mlRequested, suggestions, status, clarification, intent };
}

/**
 * Neutral fallback used only when no LLM provider is configured.
 * It intentionally does NOT invent any data or figures.
 */
function generateFallbackResponse(): string {
  return "L'assistant IA n'est pas configuré. Ajoutez une clé OPENAI_API_KEY (ou ANTHROPIC_API_KEY) dans les variables d'environnement pour activer le contrôle de la plateforme par l'IA.";
}
