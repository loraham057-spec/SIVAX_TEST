"""Analysis planner — creates multi-step analysis plans for business questions.

Given a user's business question, the planner:
1. Classifies the question type (coverage, dropout, risk, equity, etc.)
2. Determines which analysis steps are needed
3. Identifies which indicators to query
4. Produces a structured plan that the agent can execute

The plan follows the Decision Intelligence flow:
  Situation → Gap → Diagnosis → Risk → Action

Each step has:
- A tool to call (semantic_layer, indicator_query, risk_scorer, diagnostic_engine)
- Arguments for that tool
- What to extract from the previous step's results

Source: ANALYSE_AI_AGENT_DECISION_INTELLIGENCE.md §4 (analysis planner)
"""

from __future__ import annotations

import re
from typing import Any

from app.tools.semantic_layer import SemanticLayer


# Analysis step templates
STEP_TEMPLATES: dict[str, dict[str, Any]] = {
    "situation": {
        "description": "Où en sommes-nous ? — récupérer la valeur actuelle de l'indicateur principal",
        "tool": "indicator_query",
        "produces": "current_value + breakdown by province",
    },
    "gap": {
        "description": "Quel est l'écart par rapport à la cible ? — comparer au seuil OMS/national",
        "tool": "semantic_layer",
        "action": "evaluate_threshold",
        "produces": "provinces below threshold + gap magnitude",
    },
    "ranking": {
        "description": "Quelles provinces sont les plus/moins performantes ? — classement",
        "tool": "indicator_query",
        "produces": "sorted ranking of provinces",
    },
    "diagnosis": {
        "description": "Pourquoi cet écart ? — corrélations avec indicateurs secondaires",
        "tool": "diagnostic_engine",
        "action": "diagnose_gaps",
        "produces": "factors + hypotheses",
    },
    "risk_scoring": {
        "description": "Quelles zones sont les plus à risque ? — score composite",
        "tool": "risk_scorer",
        "action": "compute_risk_scores",
        "produces": "risk scores + factor contributions per province",
    },
    "comparative": {
        "description": "Quelles sont les disparités entre provinces ? — analyse comparative",
        "tool": "indicator_query",
        "produces": "comparative table + heatmap data",
    },
    "trend": {
        "description": "Quelle est l'évolution ? — tendance sur plusieurs périodes",
        "tool": "indicator_query",
        "produces": "time series + trend direction",
    },
    "action": {
        "description": "Que pourrait-on faire ? — pistes d'action basées sur le diagnostic",
        "tool": "none",  # Generated by the LLM from previous steps
        "produces": "action recommendations (human-validated)",
    },
}


class AnalysisPlanner:
    """Creates multi-step analysis plans for business questions."""

    def execute(self, action: str, args: dict) -> dict:
        if action == "create_plan":
            return self.create_plan(args)
        raise ValueError(f"Unknown analysis planner action: {action}")

    def create_plan(self, args: dict) -> dict:
        """Create an analysis plan for a business question.

        Args:
            args: {
                "question": str (the user's business question),
                "entities": dict (extracted entities from context_analysis),
                "verified_facts": dict (optional, from a previous DHIS2 query)
            }

        Returns:
            {
                "status": "ready",
                "question": str,
                "analysis_type": str,
                "steps": list of {
                    "step": str (step name),
                    "description": str,
                    "tool": str,
                    "action": str,
                    "args": dict,
                    "depends_on": list of str (previous step names),
                },
                "indicators": list of indicator definitions,
                "render_type": str (suggested render type for the frontend),
            }
        """
        question = args.get("question", "")
        entities = args.get("entities", {})
        sem = SemanticLayer()

        # Classify the question
        classification = sem.classify_question(question)
        analysis_type = classification.get("analysis_type") or "metric_value"
        catalog_entities = classification.get("entities", {})
        entities = {**catalog_entities, **{key: value for key, value in entities.items() if value not in (None, [], "")}}
        indicator_ids = classification.get("indicators", [])
        step_names = list(classification.get("steps") or ["situation"])
        qid = classification.get("qid")
        indicator_query = classification.get("indicator_query")
        response_contract = classification.get("response_contract") or sem.build_response_contract(None, question)

        # ─── User-confirmed metric (from a clarification answer) ───
        # When the user picked a specific metric in a clarification, its ID
        # is in entities["metric_id"]. Use it directly as the primary
        # indicator instead of re-classifying (which could pick a different
        # metric for a misspelled name).
        confirmed_metric_id = entities.get("metric_id")
        confirmed_metric_name = entities.get("metric_name")
        if confirmed_metric_id and confirmed_metric_id not in indicator_ids:
            indicator_ids.insert(0, confirmed_metric_id)

        # If no indicators matched, try resolving from entities
        if not indicator_ids:
            keywords = entities.get("indicator_keywords", [])
            if keywords:
                for kw in keywords:
                    result = sem.resolve_indicator(kw)
                    if result.get("best_match"):
                        indicator_ids.append(result["best_match"]["indicator_id"])
                        break

        # ─── Antigen-based indicator selection ───────────────
        # classify_question returns ALL coverage indicators (Penta3, Penta1,
        # BCG…) when the question mentions "couverture vaccinale". If the user
        # explicitly named an antigen (e.g. "BCG"), we must keep only the
        # indicator whose synonyms include that antigen — otherwise the planner
        # picks indicator_ids[0] (Penta3) and queries the wrong metric.
        antigens = entities.get("antigens") or []
        if antigens and len(indicator_ids) > 1:
            filtered = []
            for ind_id in indicator_ids:
                defn = sem.get_definition(ind_id)
                synonyms = [s.lower() for s in defn.get("synonyms", [])]
                if any(ag.lower() in synonyms for ag in antigens):
                    filtered.append(ind_id)
            if filtered:
                indicator_ids = filtered

        analysis_depth = entities.get("analysis_depth", "situation")
        if analysis_depth == "diagnosis" and "diagnosis" not in step_names:
            step_names.extend(["gap", "diagnosis"])
        elif analysis_depth == "risk" and "risk_scoring" not in step_names:
            step_names.extend(["gap", "risk_scoring", "ranking"])
        elif analysis_depth == "action" and "action" not in step_names:
            step_names.extend(["gap", "diagnosis", "action"])
        # A trend question needs the trend step so the plan reflects the
        # time-series analysis actually performed.
        if analysis_type == "trend" and "trend" not in step_names:
            step_names.append("trend")
        step_names = list(dict.fromkeys(step_names))

        # Build the plan steps
        steps: list[dict[str, Any]] = []
        primary_indicator = indicator_ids[0] if indicator_ids else None

        for i, step_name in enumerate(step_names):
            template = STEP_TEMPLATES.get(step_name, STEP_TEMPLATES["situation"])

            step: dict[str, Any] = {
                "step": step_name,
                "description": template["description"],
                "tool": template["tool"],
                "action": template.get("action"),
                "args": {},
                "depends_on": [],
            }

            # Configure step arguments based on step type
            if step_name == "situation":
                step["args"] = {
                    "indicator_ids": indicator_ids,
                    "period": entities.get("period", "LAST_3_MONTHS"),
                    "geography": entities.get("geography", "provinces"),
                }
                step["render_hint"] = "kpi_answer"

            elif step_name == "gap":
                step["args"] = {
                    "indicator_id": primary_indicator,
                }
                step["depends_on"] = ["situation"]
                step["render_hint"] = "kpi_answer"

            elif step_name == "ranking":
                step["args"] = {
                    "indicator_id": primary_indicator,
                    "sort": "descending" if primary_indicator else "descending",
                }
                step["depends_on"] = ["situation"]
                step["render_hint"] = "ranking_answer"

            elif step_name == "diagnosis":
                step["args"] = {
                    "primary_indicator": primary_indicator,
                }
                step["depends_on"] = ["situation", "gap"]
                step["render_hint"] = "diagnostic_answer"

            elif step_name == "risk_scoring":
                step["args"] = {
                    "indicators": indicator_ids,
                }
                step["depends_on"] = ["situation"]
                step["render_hint"] = "geographic_answer"

            elif step_name == "comparative":
                step["args"] = {
                    "indicator_ids": indicator_ids,
                }
                step["depends_on"] = ["situation"]
                step["render_hint"] = "comparative_answer"

            elif step_name == "trend":
                step["args"] = {
                    "indicator_id": primary_indicator,
                    "periods": entities.get("period", "LAST_12_MONTHS"),
                }
                step["render_hint"] = "trend_answer"

            elif step_name == "action":
                step["args"] = {}
                step["depends_on"] = [s["step"] for s in steps]  # depends on all previous
                step["render_hint"] = "executive_brief"

            steps.append(step)

        # Determine render type for the overall response
        render_type_map = {
            # Catalog analysis types
            "coverage": "kpi_answer",
            "dropout": "diagnostic_answer",
            "risk": "geographic_answer",
            "zero_dose": "ranking_answer",
            "equity": "comparative_answer",
            # Analytical intents (infer_analytical_intent) — without these,
            # an "évolution de X à Y" question fell back to KPI cards
            # instead of a line chart.
            "trend": "trend_answer",
            "comparison": "comparative_answer",
            "ranking": "ranking_answer",
            "diagnosis": "diagnostic_answer",
            "risk_alert": "alert_answer",
        }
        render_type = classification.get("render_type") or render_type_map.get(analysis_type, "kpi_answer")

        level_map = {"national": None, "province": 2, "health_zone": 3, "health_area": 4}
        requested_levels = entities.get("geographic_levels") or []
        breakdown = entities.get("breakdown")
        target_level = level_map.get(breakdown or (requested_levels[0] if requested_levels else ""))
        visualization_map = {
            "kpi_answer": "kpi",
            "ranking_answer": "bar",
            "trend_answer": "line",
            "diagnostic_answer": "bar",
            "geographic_answer": "bar",
            "comparative_answer": "bar",
            "alert_answer": "line",
            "executive_brief": "table",
        }
        # The user's explicit visualization request ("courbe", "camembert"…)
        # extracted by context_analysis takes precedence over the mapping.
        user_visualization = entities.get("visualization")
        if user_visualization not in ("line", "bar", "pie", "kpi", "table"):
            user_visualization = None
        indicator_keywords = entities.get("indicator_keywords") or []
        query_text = indicator_query or (indicator_keywords[0] if indicator_keywords else question)
        requested_period = entities.get("period") or "LAST_12_MONTHS"
        explicit_periods = entities.get("periods") or []
        # If the LLM extracted a single year/month as "period" but the
        # deterministic extractor already produced explicit period codes
        # (e.g. quarter months 202604,202605,202606), keep the deterministic
        # ones — they are more precise and not subject to LLM hallucination.
        if not explicit_periods and isinstance(requested_period, str) and len(requested_period) in (4, 6) and requested_period.isdigit():
            explicit_periods = [requested_period]
            requested_period = "LAST_12_MONTHS"
        valid_presets = {
            "THIS_MONTH", "LAST_MONTH", "THIS_YEAR", "LAST_YEAR",
            "LAST_3_MONTHS", "LAST_6_MONTHS", "LAST_12_MONTHS", "YEAR_OVER_YEAR",
        }
        if requested_period not in valid_presets:
            requested_period = "LAST_12_MONTHS"
        action_args: dict[str, Any] = {
            "question": question,
            "metricQuery": query_text,
            "periodPreset": requested_period,
            "visualization": user_visualization or visualization_map.get(render_type, "auto"),
            "qid": qid or "",
            "analysisIntent": analysis_type,
            "measurementType": response_contract.get("measurement_type", "value"),
            "renderType": render_type,
        }
        if primary_indicator:
            primary_definition = sem.get_definition(primary_indicator)
            action_args["metricId"] = primary_indicator
            action_args["metricName"] = (
                confirmed_metric_name
                or primary_definition.get("name")
                or query_text
            )
        # Default to province-level breakdown for national coverage questions
        # that don't specify a geographic level. Without this, the analytics
        # query returns a single national aggregate instead of per-province data.
        if not target_level and not entities.get("geographic_levels"):
            if analysis_type in ("coverage", "metric_value") and entities.get("antigens"):
                target_level = 2
        if target_level:
            action_args["targetOrgUnitLevel"] = target_level
        if response_contract.get("threshold") is not None:
            action_args["threshold"] = response_contract["threshold"]
        if response_contract.get("comparison_operator"):
            action_args["comparisonOperator"] = response_contract["comparison_operator"]
        # ─── Annual period collapse ──────────────────────────
        # When the user says "l'année 2025" (periodicity=annual), the entity
        # extractor produces 12 monthly codes [202501..202512]. DHIS2 stores
        # coverage as a monthly indicator, but the ANNUAL aggregate (filter
        # pe:2025) is the correct value to show — monthly values are ~8% (one
        # month of coverage) while the annual aggregate is ~90% (full year).
        # Collapse 12 monthly periods of the same year into a single annual
        # period code so the DHIS2 query uses filter=pe:2025.
        if explicit_periods and entities.get("periodicity") == "annual":
            years = set()
            all_monthly = True
            for p in explicit_periods:
                if re.match(r"^\d{6}$", p):
                    years.add(p[:4])
                elif re.match(r"^\d{4}$", p):
                    years.add(p)
                    all_monthly = False
                else:
                    all_monthly = False
            if all_monthly and len(years) == 1 and len(explicit_periods) == 12:
                explicit_periods = [list(years)[0]]
        if explicit_periods:
            action_args["periods"] = explicit_periods

        multi_antigen_qids = {
            "taux_perte_vaccins",
            "proportion_disponibilite_vaccins_seuil",
            "taux_consommation_vaccins",
        }
        antigens = entities.get("antigens") or []
        if qid in multi_antigen_qids and antigens:
            executable_actions = []
            for antigen in antigens:
                antigen_args = {
                    **action_args,
                    "metricQuery": f"{query_text} {antigen}",
                    "antigens": [antigen],
                }
                antigen_args.pop("metricId", None)
                antigen_args.pop("metricName", None)
                executable_actions.append({"action": "run_dhis2_analysis", "args": antigen_args})
        else:
            if antigens:
                action_args["antigens"] = antigens
            executable_actions = [{"action": "run_dhis2_analysis", "args": action_args}]

        comparison_baseline = entities.get("comparison_baseline")
        if entities.get("comparison_mode") == "previous_analysis" and comparison_baseline:
            baseline_args = {
                **action_args,
                "question": f"Référence précédente : {comparison_baseline.get('metric_name') or query_text}",
                "metricQuery": comparison_baseline.get("metric_name") or query_text,
                "orgUnitId": comparison_baseline.get("org_unit_id"),
                "periods": comparison_baseline.get("periods") or explicit_periods,
                "renderType": "comparative_answer",
                "visualization": "bar",
            }
            if comparison_baseline.get("metric_id"):
                baseline_args["metricId"] = comparison_baseline["metric_id"]
                baseline_args["metricName"] = comparison_baseline.get("metric_name") or query_text
            executable_actions.insert(0, {"action": "run_dhis2_analysis", "args": baseline_args})
            render_type = "comparative_answer"

        # Get indicator definitions
        indicator_defs = []
        for uid in indicator_ids:
            defn = sem.get_definition(uid)
            if defn.get("status") == "ready":
                indicator_defs.append({
                    "id": uid,
                    "name": defn.get("name"),
                    "short_name": defn.get("short_name"),
                    "unit": defn.get("unit"),
                    "thresholds": defn.get("thresholds"),
                    "definition": defn.get("definition"),
                })

        return {
            "status": "ready",
            "question": question,
            "qid": qid,
            "classification_confidence": classification.get("confidence", 0.0),
            "analysis_type": analysis_type,
            "domain": classification.get("domain"),
            "resolution_mode": classification.get("resolution_mode"),
            "mapping_status": classification.get("mapping_status"),
            "entities": entities,
            "steps": steps,
            "indicators": indicator_defs,
            "indicator_query": query_text,
            "render_type": render_type,
            "response_contract": response_contract,
            "primary_indicator": primary_indicator,
            "executable_actions": executable_actions,
        }
